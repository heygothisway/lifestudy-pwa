// 取得篇章官方線上網址
// 規則：第 1 篇為 {bookId}.html，第 2 篇以上為 {bookId}_{msgNum}.html
function getLifeStudyUrl(bookId, msgNum) {
  if (parseInt(msgNum, 10) === 1) {
    return `https://line.twgbr.org/life-study/${bookId}.html`;
  }
  return `https://line.twgbr.org/life-study/${bookId}_${msgNum}.html`;
}
